    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            double price = 0;
            String load = "SELECT price FROM subject_count_prices WHERE count = '" + subjectcount.getText() + "'";
            ResultSet rs = Database.DB.search(load);
            while (rs.next()) {
                price = rs.getDouble("price");
            }
            if (subjectcount.getText().isEmpty() || primaryprice.getText().isEmpty()) {
                JOptionPane.showMessageDialog(rootPane, "FIRST SELECT THE ONE YOU WANT TO UPDATE");
            } else {
                if (price == Double.valueOf(primaryprice.getText())) {
                    JOptionPane.showMessageDialog(rootPane, "CURRUNTLY PRICE IS SAME AS YOU ENTERED");
                } else {
                    String update = "UPDATE subject_count_prices SET price = '" + Double.valueOf(primaryprice.getText()) + "' WHERE count = '" + subjectcount.getText() + "'";
                    Database.DB.IUD(update);
                    JOptionPane.showMessageDialog(rootPane, "UPDATED");
                    DefaultTableModel model = (DefaultTableModel) primary.getModel();
                    model.setRowCount(0);

                    String load2 = "SELECT * FROM subject_count_prices";
                    ResultSet rs2 = Database.DB.search(load2);
                    DefaultTableModel df = (DefaultTableModel) primary.getModel();
                    while (rs2.next()) {
                        Vector v = new Vector();
                        v.add(rs2.getString("count"));
                        v.add(rs2.getString("price"));
                        df.addRow(v);
                    }
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

