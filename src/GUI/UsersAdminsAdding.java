    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        try {
            if (username.getText().isEmpty() || password.getText().isEmpty() || email.getText().isEmpty()) {
                JOptionPane.showMessageDialog(rootPane, "FILL ALL THE BLANK FIELDS");
            } else {
                if (type.getSelectedItem().toString().equals("User")) {
                    String un = "";
                    String em = "";
                    String search = "SELECT username,email FROM user";
                    ResultSet rs = Database.DB.search(search);
                    while (rs.next()) {
                        un = rs.getString("username");
                        em = rs.getString("email");
                    }
                    if (un.equals(username.getText()) || em.equals(email.getText())) {
                        JOptionPane.showMessageDialog(rootPane, "THIS USERNAME OR EMAIL IS ALREADY TAKEN");
                        username.setText(null);
                        email.setText(null);
                    } else {
                        String add = "INSERT INTO user(username,password,email)VALUES('" + username.getText() + "','" + password.getText() + "','" + email.getText() + "')";
                        Database.DB.IUD(add);
                        JOptionPane.showMessageDialog(rootPane, "USER ADDED");
                        this.dispose();
                        new UsersAdminsAdding().setVisible(true);
                    }
                } else {
                    String un = "";
                    String em = "";
                    String search = "SELECT username,email FROM admin";
                    ResultSet rs = Database.DB.search(search);
                    while (rs.next()) {
                        un = rs.getString("username");
                        em = rs.getString("email");
                    }
                    if (un.equals(username.getText()) || em.equals(email.getText())) {
                        JOptionPane.showMessageDialog(rootPane, "THIS USERNAME OR EMAIL IS ALREADY TAKEN");
                        username.setText(null);
                        email.setText(null);
                    } else {
                        String add = "INSERT INTO admin(username,password,email)VALUES('" + username.getText() + "','" + password.getText() + "','" + email.getText() + "')";
                        Database.DB.IUD(add);
                        JOptionPane.showMessageDialog(rootPane, "ADMIN ADDED");
                        this.dispose();
                        new UsersAdminsAdding().setVisible(true);
                    }
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton5ActionPerformed

    private void emailKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_emailKeyPressed
        if (!(Pattern.matches("^[a-zA-Z0-9]+[@]{1}+[a-zA-Z0-9]+[.]{1}+[a-zA-Z0-9]+$", email.getText()))) {
            email.setForeground(Color.red);
        } else {
            email.setForeground(Color.green);
        }
    }//GEN-LAST:event_emailKeyPressed

    private void usernameKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_usernameKeyReleased
        int position = username.getCaretPosition();
        username.setText(username.getText().toUpperCase());
        username.setCaretPosition(position);
    }//GEN-LAST:event_usernameKeyReleased

