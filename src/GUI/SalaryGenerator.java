    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if (lecturer.getText().isEmpty() || salaryamount.getText().isEmpty() || month.getText().isEmpty() || institiutecost.getText().isEmpty()) {
            JOptionPane.showMessageDialog(rootPane, "FIRST CHOOSE THE LECTURER");
        } else {
            String lec = null;
            String cat = null;
            String mon = null;
            try {
                String search = "SELECT * FROM salary_paid WHERE lecturer = '" + lecturer.getText() + "' AND category = '" + grade.getSelectedItem().toString() + "' AND month = '" + month.getText() + "'";
                ResultSet rs = Database.DB.search(search);
                while (rs.next()) {
                    lec = rs.getString("lecturer");
                    cat = rs.getString("category");
                    mon = rs.getString("month");
                }

                if (lecturer.getText().equals(lec) && grade.getSelectedItem().toString().equals(cat) && month.getText().equals(mon)) {
                    JOptionPane.showMessageDialog(rootPane, "ALREADY PAID");
                } else {
                    String add = "INSERT INTO salary_paid(lecturer,category,salary_amount,month,institute_cost)VALUES('" + lecturer.getText() + "','" + grade.getSelectedItem().toString() + "','" + Double.valueOf(salaryamount.getText()) + "','" + month.getText() + "','" + Double.valueOf(institiutecost.getText()) + "')";
                    Database.DB.IUD(add);
                    JOptionPane.showMessageDialog(rootPane, "PAID");
                }
            } catch (Exception e) {
                e.printStackTrace();
            }
        }

    }//GEN-LAST:event_jButton1ActionPerformed

    private void salarytableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_salarytableMouseClicked
        try {
            DefaultTableModel df = (DefaultTableModel) salarytable.getModel();
            int selectRowIndex = salarytable.getSelectedRow();

            String sa = df.getValueAt(selectRowIndex, 1).toString();
            double salary = Double.parseDouble(sa);
            double instcost = salary / 4;
            double sal = salary - instcost;

            lecturer.setText(df.getValueAt(selectRowIndex, 0).toString());
            salaryamount.setText(String.valueOf(sal));

            institiutecost.setText(String.valueOf(instcost));
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_salarytableMouseClicked

