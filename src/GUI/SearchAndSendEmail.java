    private void datePropertyChange(java.beans.PropertyChangeEvent evt) {//GEN-FIRST:event_datePropertyChange
        try {
            Date date2 = date.getDate();
            SimpleDateFormat formatter = new SimpleDateFormat("yyyy-MM-dd");
            String dat = formatter.format(date2);
            DefaultTableModel model = (DefaultTableModel) attendance_table.getModel();
            model.setRowCount(0);
            String search = "SELECT * FROM attendance WHERE date = '" + dat + "' AND status = '" + status.getSelectedItem().toString() + "'";
            ResultSet rs = Database.DB.search(search);
            DefaultTableModel df = (DefaultTableModel) attendance_table.getModel();
            while (rs.next()) {
                Vector v = new Vector();
                v.add(rs.getString("admission_no"));
                v.add(rs.getString("name"));
                v.add(rs.getString("c_email"));
                v.add(rs.getString("subject"));
                v.add(rs.getString("grade"));
                v.add(rs.getString("date"));
                df.addRow(v);
            }

        } catch (Exception e) {

        }
    }//GEN-LAST:event_datePropertyChange

