    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if (admission_no.getText().isEmpty() || name.getText().isEmpty() || paymentmonth.getDate() == null) {
            JOptionPane.showMessageDialog(null, "FILL ALL THE BLANK FIELDS");
        } else {
            try {

                String aa = "There is nothing";
                String bb = "There is nothing";
                String cc = "There is nothing";

                String search = "SELECT * FROM students_payments WHERE admission_no = '" + admission_no.getText() + "'";
                ResultSet rs1 = Database.DB.search(search);
                while (rs1.next()) {
                    aa = rs1.getString("admission_no");
                    bb = rs1.getString("month");
                    cc = rs1.getString("status");
                }

                Date date3 = paymentmonth.getDate();
                String paymentmonth = DateFormat.getDateInstance().format(date3);
                String dt1 = new SimpleDateFormat("MMM, yyyy").format(date3);
                String stringExcerpt1 = bb.substring(0, 3);
                String stringExcerpt2 = bb.substring(6, 11);
                String fix = stringExcerpt1 + "," + stringExcerpt2;

                if (admission_no.getText().equals(aa) && dt1.equals(fix) && cc.equals("Done")) {
                    JOptionPane.showMessageDialog(null, "ALREADY PAID");
                } else {
                    if (admission_no.getText().equals(aa) && dt1.equals(fix) && cc.equals("Pending")) {
                        JOptionPane.showMessageDialog(null, "SELECTED MONTH PAYMENT IS PENDING");
                    } else {
                        String add = "INSERT INTO students_payments(admission_no,month,status)VALUES('" + admission_no.getText() + "','" + paymentmonth + "','" + status.getSelectedItem().toString() + "')";
                        Database.DB.IUD(add);
                        JOptionPane.showMessageDialog(null, "DONE");
                        this.dispose();
                        new StudentPayments().setVisible(true);
                    }
                }
            } catch (Exception e) {
                e.printStackTrace();
            }
        }


    }//GEN-LAST:event_jButton1ActionPerformed

