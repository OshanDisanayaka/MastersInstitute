            ResultSet rss = Database.DB.search(paymentmon);
            while (rss.next()) {
                month = rss.getString("month");
            }

            java.util.Date date3 = paymentmonth.getDate();
            String paymentmonth = DateFormat.getDateInstance().format(date3);
