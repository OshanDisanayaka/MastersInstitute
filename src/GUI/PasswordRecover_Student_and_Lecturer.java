    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        try {
            int ii = accounts.getSelectedRow();
            if (ii == -1) {
                JOptionPane.showMessageDialog(null, "FIRST SELECT THE STUDENT");
            } else {
                int username = 0;
                String password = null;
                String email = null;

                DefaultTableModel df = (DefaultTableModel) accounts.getModel();
                int i = accounts.getSelectedRow();
                username = Integer.valueOf(df.getValueAt(i, 0).toString());

                if (selector.getSelectedItem().equals("LECTURERS")) {
                    String it2 = "SELECT password FROM lecturer_account WHERE username ='" + username + "'";
                    ResultSet r4 = Database.DB.search(it2);
                    while (r4.next()) {
                        password = r4.getString("password");
                    }
                } else {
                    String it2 = "SELECT password FROM student_account WHERE username ='" + username + "'";
                    ResultSet r4 = Database.DB.search(it2);
                    while (r4.next()) {
                        password = r4.getString("password");
                    }
                }

                email = df.getValueAt(i, 1).toString();

                String host = Database.AppConfig.get("mail.host", "smtp.gmail.com");
                String user = Database.AppConfig.get("mail.user");
                String pass = Database.AppConfig.get("mail.password");
                String to = email;
                String from = Database.AppConfig.get("mail.from", user);
                String subject = "Masters Institute Administration Office";
                String messageText = "Your username and password" + "\n" + "\n" + "Username : " + username + "\n" + "Password : " + password;
                boolean sessionDebug = false;

                Properties props = System.getProperties();

                props.put("mail.smtp.starttls.enable", "true");
                props.put("mail.smtp.host", host);
                props.put("mail.smtp.port", Database.AppConfig.get("mail.port", "587"));
                props.put("mail.smtp.auth", "true");
                props.put("mail.smtp.starttls.required", "true");


                Session mailSession = Session.getDefaultInstance(props, null);
                mailSession.setDebug(sessionDebug);
                Message msg = new MimeMessage(mailSession);
                msg.setFrom(new InternetAddress(from));
                InternetAddress[] address = {new InternetAddress(to)};
                msg.setRecipients(Message.RecipientType.TO, address);
                msg.setSubject(subject);
                msg.setSentDate(new Date());
                msg.setText(messageText);

                Transport transport = mailSession.getTransport("smtp");
                transport.connect(host, user, pass);
                transport.sendMessage(msg, msg.getAllRecipients());
                transport.close();

                JOptionPane.showMessageDialog(null, "ACCOUNT DETAILS SENT TO THE EMAIL");
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton5ActionPerformed

