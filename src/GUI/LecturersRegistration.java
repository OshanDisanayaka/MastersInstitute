    private void emailKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_emailKeyPressed
        if (!(Pattern.matches("^[a-zA-Z0-9]+[@]{1}+[a-zA-Z0-9]+[.]{1}+[a-zA-Z0-9]+$", email.getText()))) {
            email.setForeground(Color.red);
        } else {
            email.setForeground(Color.green);
        }
    }//GEN-LAST:event_emailKeyPressed

    private void formWindowOpened(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowOpened
        try {
            int id = 0;
            String search = "SELECT MAX(lecturer_id) FROM lecturers";
            ResultSet rs = Database.DB.search(search);
            while (rs.next()) {
                id = rs.getInt("MAX(lecturer_id)");
            }
            if (id == 0) {
                lectureid.setText("10" + "1");
            } else {
                int total = id + 1;
                lectureid.setText(String.valueOf(total));
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_formWindowOpened

