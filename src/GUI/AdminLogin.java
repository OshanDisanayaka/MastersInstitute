    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        if (username.getText().isEmpty() || password.getText().isEmpty()) {
            JOptionPane.showMessageDialog(rootPane, "USERNAME OR PASSWORD IS NOT GIVEN");
        } else {
            try {
                String un = "";
                String pw = "";
                String search = "SELECT username,password FROM admin";
                ResultSet rs = Database.DB.search(search);
                while (rs.next()) {
                    un = rs.getString("username");
                    pw = rs.getString("password");
                }
                if (un.equals(username.getText()) && pw.equals(password.getText())) {
                    this.dispose();
                    new AdminPanel().setVisible(true);
                } else {
                    JOptionPane.showMessageDialog(rootPane, "USERNAME OR PASSWORD IS INCORRECT");
                    username.setText(null);
                    password.setText(null);
                }
            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_jButton4ActionPerformed

