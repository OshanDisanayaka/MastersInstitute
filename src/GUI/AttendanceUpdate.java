    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        try {
            String update = "UPDATE attendance SET status  ='" + status.getSelectedItem().toString() + "' WHERE admission_no = '" + admission_no.getText() + "' AND subject = '" + subject.getText() + "' AND grade = '" + grade.getText() + "' AND date = '" + date.getText() + "' ";
            Database.DB.IUD(update);
            JOptionPane.showMessageDialog(rootPane, "UPDATED");
            this.dispose();
            new SearchAndSendEmail().setVisible(true);
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        try {
            String status = null;
            String it2 = "SELECT status FROM menu WHERE id ='1'";
            ResultSet r4 = Database.DB.search(it2);
            while (r4.next()) {
                status = r4.getString("status");
            }
            if (UserSession.isAdmin(status)) {
                new AdminPanel().setVisible(true);
                this.dispose();
            } else {
                this.dispose();
                new Menu().setVisible(true);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton4ActionPerformed

