    /** Clean, symmetric dashboard layout (see DashboardLayout). */
    private void arrangeDashboard() {
        DashboardLayout.on(jPanel1)
                .header(jLabel5)
                .footer(jLabel4)
                .banner(jLabel6)
                .time(jLabel7, time)
                .date(jLabel8, date)
                .row(DashboardLayout.section(jLabel1, 4, 1,
                        jButton7, jButton8, jButton9, jButton11,
                        jButton19, jButton18, jButton10, jButton12))
                .row(DashboardLayout.section(jLabel2, 3, 3,
                        jButton13, jButton15, jButton14, jButton16, jButton17),
                        DashboardLayout.section(jLabel3, 1, 1,
                                jButton20, jButton22))
                .apply();
    }

    public void scaleImage() {
        ImageIcon icon = new ImageIcon(getClass().getResource("/Images/adminpanel.png"));
        Image img = icon.getImage();
        Image imgScale = img.getScaledInstance(jLabel6.getWidth(), jLabel6.getHeight(), Image.SCALE_SMOOTH);
        ImageIcon scaledIcon = new ImageIcon(imgScale);
        jLabel6.setIcon(scaledIcon);
    }

    public void Date() {
        SimpleDateFormat formatter = new SimpleDateFormat("yyyy-MM-dd");
        Date date = new Date(System.currentTimeMillis());
        this.date.setText(formatter.format(date));

        SimpleDateFormat formatter1 = new SimpleDateFormat("HH:mm:ss aa");
        Date date1 = new Date(System.currentTimeMillis());
        this.time.setText(formatter1.format(date1));
    }

    public void Time() {
        new Timer(0, new ActionListener() {
            @Override
            public void actionPerformed(ActionEvent e) {
                Date d = new Date();
                SimpleDateFormat s = new SimpleDateFormat("hh:mm:ss aa");
                String tim = s.format(d);
                time.setText(tim);
            }
        }).start();
    }

