    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        if (students_table.getSelectionModel().isSelectionEmpty()) {
            JOptionPane.showMessageDialog(rootPane, "FIRST SELECT THE ONE YOU WANT TO DELETE");
        } else {
            try {
                int id = 0;
                String month = "";
                DefaultTableModel df = (DefaultTableModel) students_table.getModel();
                for (int i = 0; i < df.getRowCount(); i++) {
                    id = Integer.valueOf(df.getValueAt(i, 0).toString());
                    month = df.getValueAt(i, 1).toString();
                }
                String delete = "DELETE FROM students_payments WHERE admission_no  = '" + id + "' AND month = '" + month + "'";
                Database.DB.IUD(delete);
                JOptionPane.showMessageDialog(rootPane, "DELETED");
                df.removeRow(students_table.getSelectedRow());
            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_jButton4ActionPerformed

    private void formWindowOpened(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowOpened
        try {
            String search = "SELECT * FROM students_payments";
            ResultSet rs = Database.DB.search(search);
            DefaultTableModel df = (DefaultTableModel) students_table.getModel();
            while (rs.next()) {
                Vector v = new Vector();
                v.add(rs.getString("admission_no"));
                v.add(rs.getString("month"));
                v.add(rs.getString("status"));
                df.addRow(v);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_formWindowOpened

    private void searchbarKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_searchbarKeyReleased
        try {
            String search = "SELECT * FROM students_payments WHERE admission_no LIKE '%" + searchbar.getText() + "%'";
            ResultSet rs = Database.DB.search(search);
            DefaultTableModel df = (DefaultTableModel) students_table.getModel();
            int a = df.getRowCount();
            for (int i = 0; i < a; i++) {
                df.removeRow(0);
            }
            while (rs.next()) {
                Vector v = new Vector();
                v.add(rs.getString("admission_no"));
                v.add(rs.getString("month"));
                v.add(rs.getString("status"));
                df.addRow(v);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_searchbarKeyReleased

    private void searchbarKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_searchbarKeyTyped
        char c = evt.getKeyChar();
        if (!Character.isDigit(c)) {
            evt.consume();
        }
    }//GEN-LAST:event_searchbarKeyTyped

