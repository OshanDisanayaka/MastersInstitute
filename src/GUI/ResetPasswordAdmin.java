    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed
        try {
            if (username.getText().isEmpty() || cpassword.getText().isEmpty() || npassword.getText().isEmpty() || cnpassword.getText().isEmpty()) {
                JOptionPane.showMessageDialog(rootPane, "SOME REQUIRED FILED IS EMPTY");
            } else {
                if (!npassword.getText().equals(cnpassword.getText())) {
                    JOptionPane.showMessageDialog(rootPane, "NEW PASSWORD IS DOES NOT MATCH");
                    npassword.setText(null);
                    cnpassword.setText(null);
                } else {
                    String un = "";
                    String pw = "";
                    String search = "SELECT username,password FROM admin";
                    ResultSet rs = Database.DB.search(search);
                    while (rs.next()) {
                        un = rs.getString("username");
                        pw = rs.getString("password");
                    }
                    if (username.getText().equals(un) && cpassword.getText().equals(pw)) {
                        String update = "UPDATE admin SET password  = '" + npassword.getText() + "' WHERE username = '" + username.getText() + "'";
                        Database.DB.IUD(update);
                        JOptionPane.showMessageDialog(rootPane, "PASSWORD IS UPDATED");
                        this.dispose();
                        new AdminLogin().setVisible(true);
                    } else {
                        JOptionPane.showMessageDialog(rootPane, "ENTERED USERNAME OR CURRENT PASSWORD IS INCORRECT");
                        this.dispose();
                        new AdminLogin().setVisible(true);
                    }
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }

    }//GEN-LAST:event_jButton7ActionPerformed

