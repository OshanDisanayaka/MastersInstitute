    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed
        if (username.getText().isEmpty() || email.getText().isEmpty()) {
            JOptionPane.showMessageDialog(rootPane, "USERNAME OR EMAIL IS NOT GIVEN");
        } else {
            try {
                String un = "";
                String em = "";
                String pw = "";
                String search = "SELECT username,email FROM user";
                ResultSet rs = Database.DB.search(search);
                while (rs.next()) {
                    un = rs.getString("username");
                    em = rs.getString("email");
                }
                if (un.equals(username.getText()) && em.equals(email.getText())) {
                    String search2 = "SELECT password FROM user WHERE username = '" + username.getText() + "'";
                    ResultSet rs2 = Database.DB.search(search2);
                    while (rs2.next()) {
                        pw = rs2.getString("password");
                    }

                    String host = Database.AppConfig.get("mail.host", "smtp.gmail.com");
                    String user = Database.AppConfig.get("mail.user");
                    String pass = Database.AppConfig.get("mail.password");
                    String to = email.getText();
                    String from = Database.AppConfig.get("mail.from", user);
                    String subject = "Masters Institute Administration Office";
                    String messageText = "Your Masters Institute's user account password is " + pw;
                    boolean sessionDebug = false;

                    Properties props = System.getProperties();

                    props.put("mail.smtp.starttls.enable", "true");
                    props.put("mail.smtp.host", host);
                    props.put("mail.smtp.port", Database.AppConfig.get("mail.port", "587"));
                    props.put("mail.smtp.auth", "true");
                    props.put("mail.smtp.starttls.required", "true");


                    Session mailSession = Session.getDefaultInstance(props, null);
                    mailSession.setDebug(sessionDebug);
                    Message msg = new MimeMessage(mailSession);
                    msg.setFrom(new InternetAddress(from));
                    InternetAddress[] address = {new InternetAddress(to)};
                    msg.setRecipients(Message.RecipientType.TO, address);
                    msg.setSubject(subject);
                    msg.setSentDate(new Date());
                    msg.setText(messageText);

                    Transport transport = mailSession.getTransport("smtp");
                    transport.connect(host, user, pass);
                    transport.sendMessage(msg, msg.getAllRecipients());
                    transport.close();
                    JOptionPane.showMessageDialog(rootPane, "YOUR PASSWORD IS SENT TO THE EMAIL");
                    this.dispose();
                    new UserLogin().setVisible(true);
                } else {
                    JOptionPane.showMessageDialog(rootPane, "THERE IS NO USER ACCOUNT RELATED TO THIS GIVEN USERNAME AND EMAIL");
                    username.setText(null);
                    email.setText(null);
                }
            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_jButton7ActionPerformed

    private void emailKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_emailKeyPressed
        if (!(Pattern.matches("^[a-zA-Z0-9]+[@]{1}+[a-zA-Z0-9]+[.]{1}+[a-zA-Z0-9]+$", email.getText()))) {
            email.setForeground(Color.red);
        } else {
            email.setForeground(Color.green);
        }

    }//GEN-LAST:event_emailKeyPressed

