    private void searchbarKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_searchbarKeyReleased
        try {
            String search = "SELECT * FROM lecturers WHERE lecturer_id LIKE '%" + searchbar.getText() + "%'";
            ResultSet rs = Database.DB.search(search);
            DefaultTableModel df = (DefaultTableModel) lecturers.getModel();
            int a = df.getRowCount();
            for (int i = 0; i < a; i++) {
                df.removeRow(0);
            }
            while (rs.next()) {
                Vector v = new Vector();
                v.add(rs.getString("lecturer_id"));
                v.add(rs.getString("name"));
                v.add(rs.getString("contact"));
                v.add(rs.getString("email"));
                v.add(rs.getString("address"));
                df.addRow(v);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_searchbarKeyReleased

