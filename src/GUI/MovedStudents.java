    private void formWindowOpened(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowOpened
        try {
            DefaultTableModel model = (DefaultTableModel) students_table.getModel();
            model.setRowCount(0);
            String search = "SELECT * FROM student WHERE grade = '" + grade.getSelectedItem().toString() + "'";
            ResultSet rs = Database.DB.search(search);
            DefaultTableModel df = (DefaultTableModel) students_table.getModel();
            while (rs.next()) {
                Vector v = new Vector();
                v.add(rs.getString("admission_no"));
                v.add(rs.getString("name"));
                v.add(rs.getString("gender"));
                v.add(rs.getString("grade"));
                df.addRow(v);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_formWindowOpened

