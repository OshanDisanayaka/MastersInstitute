    private void jButton8ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton8ActionPerformed
        if (type.getSelectedItem().toString().equals("ADMINS")) {
            if (jTable1.getSelectionModel().isSelectionEmpty()) {
                JOptionPane.showMessageDialog(rootPane, "FIRST SELECT THE ONE YOU WANT TO DELETE");
            } else {
                try {
                    String un = "";
                    DefaultTableModel df = (DefaultTableModel) jTable1.getModel();
                    for (int i = 0; i < df.getRowCount(); i++) {
                        un = df.getValueAt(i, 0).toString();
                    }
                    String delete = "DELETE FROM admin WHERE username  = '" + un + "'";
                    Database.DB.IUD(delete);
                    JOptionPane.showMessageDialog(rootPane, "DELETED");
                    df.removeRow(jTable1.getSelectedRow());
                } catch (Exception e) {
                    e.printStackTrace();
                }
            }
        } else {
            if (jTable1.getSelectionModel().isSelectionEmpty()) {
                JOptionPane.showMessageDialog(rootPane, "FIRST SELECT THE ONE YOU WANT TO DELETE");
            } else {
                try {
                    String un = "";
                    DefaultTableModel df = (DefaultTableModel) jTable1.getModel();
                    for (int i = 0; i < df.getRowCount(); i++) {
                        un = df.getValueAt(i, 0).toString();
                    }
                    String delete = "DELETE FROM user WHERE username  = '" + un + "'";
                    Database.DB.IUD(delete);
                    JOptionPane.showMessageDialog(rootPane, "DELETED");
                    df.removeRow(jTable1.getSelectedRow());
                } catch (Exception e) {
                    e.printStackTrace();
                }
            }
        }
    }//GEN-LAST:event_jButton8ActionPerformed

    private void typeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_typeActionPerformed
        try {
            if (type.getSelectedItem().toString().equals("ADMINS")) {
                DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
                model.setRowCount(0);
                String search = "SELECT * FROM admin";
                ResultSet rs = Database.DB.search(search);
                DefaultTableModel df = (DefaultTableModel) jTable1.getModel();
                while (rs.next()) {
                    Vector v = new Vector();
                    v.add(rs.getString("username"));
                    v.add(rs.getString("email"));
                    df.addRow(v);
                }
            } else {
                DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
                model.setRowCount(0);
                String search = "SELECT * FROM user";
                ResultSet rs = Database.DB.search(search);
                DefaultTableModel df = (DefaultTableModel) jTable1.getModel();
                while (rs.next()) {
                    Vector v = new Vector();
                    v.add(rs.getString("username"));
                    v.add(rs.getString("email"));
                    df.addRow(v);
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_typeActionPerformed

