    private void formWindowOpened(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowOpened
        try {
            int id = 0;
            String search = "SELECT MAX(admission_no) FROM student";
            ResultSet rs = Database.DB.search(search);
            while (rs.next()) {
                id = rs.getInt("MAX(admission_no)");
            }
            if (id == 0) {
                admission_no.setText("100" + "1");
            } else {
                int total = id + 1;
                admission_no.setText(String.valueOf(total));
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_formWindowOpened

