    private void searchbarKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_searchbarKeyReleased
        try {
            String search = "SELECT * FROM student WHERE (admission_no LIKE '%" + searchbar.getText() + "%') AND grade =  '" + grade.getSelectedItem().toString() + "'";
            ResultSet rs = Database.DB.search(search);
            DefaultTableModel df = (DefaultTableModel) students_table.getModel();
            int a = df.getRowCount();
            for (int i = 0; i < a; i++) {
                df.removeRow(0);
            }
            while (rs.next()) {
                Vector v = new Vector();
                v.add(rs.getString("admission_no"));
                v.add(rs.getString("name"));
                v.add(rs.getString("gender"));
                v.add(rs.getString("grade"));
                v.add(rs.getString("leaving"));
                df.addRow(v);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_searchbarKeyReleased

