    /** Clean, symmetric dashboard layout (see DashboardLayout). */
    private void arrangeDashboard() {
        DashboardLayout.on(jPanel1)
                .header(jLabel3)
                .footer(jLabel4)
                .banner(masters)
                .time(jLabel5, time)
                .date(jLabel7, date)
                .row(DashboardLayout.section(jLabel1, 4, 3,
                        jButton7, jButton8, jButton9, jButton11,
                        jButton19, jButton18, jButton10, jButton12),
                        DashboardLayout.section(jLabel2, 1, 1,
                                jButton13, jButton17))
                .apply();
    }

    public void scaleImage() {
        ImageIcon icon = new ImageIcon(getClass().getResource("/Images/1.jpg"));

        Image img = icon.getImage();
        Image imgScale = img.getScaledInstance(masters.getWidth(), masters.getHeight(), Image.SCALE_SMOOTH);
        ImageIcon scaledIcon = new ImageIcon(imgScale);
        masters.setIcon(scaledIcon);
    }

    public void Date() {
        SimpleDateFormat formatter = new SimpleDateFormat("yyyy-MM-dd");
        Date date = new Date(System.currentTimeMillis());
        this.date.setText(formatter.format(date));
    }

    public void Time() {
        new Timer(0, new ActionListener() {
            @Override
            public void actionPerformed(ActionEvent e) {
                Date d = new Date();
                SimpleDateFormat s = new SimpleDateFormat("hh:mm:ss aa");
                String tim = s.format(d);
                time.setText(tim);
            }
        }).start();
    }

    public void status() {
        try {
            UserSession.setRole("USER");
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

